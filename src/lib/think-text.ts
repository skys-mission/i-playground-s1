/** 思维链展示文本净化：推理摘要常自带 Markdown 记号（**加粗**、`代码`、行首 #），
 *  而思维链盒子按纯文本渲染，这里把记号剥掉只留内容。
 *  刻意不处理 _下划线_ 强调：思维里常见 snake_case 标识符，误伤代价大于收益 */

export function plainThinkText(s: string): string {
  return s
    // **加粗** → 内容
    .replace(/\*\*([^*\n]+)\*\*/g, "$1")
    // *斜体* → 内容：开星号须在行首/空白/开引号后，闭星号后须是空白/标点/行尾，
    // 借此避开 2*3*4 这类乘法与「* 」列表符
    .replace(/(^|[\s（(【「'“，。：；、])\*([^*\s][^*\n]*?)\*(?=[\s)）】」'”，。：；、,.!?]|$)/gm, "$1$2")
    // 行首标题记号 # ~ ######
    .replace(/^#{1,6}[ \t]+/gm, "")
    // `代码` → 内容
    .replace(/`([^`\n]+)`/g, "$1");
}
